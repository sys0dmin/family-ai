function element(tag, className, text) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}

function searchableText(topic) {
  return [
    topic.title,
    topic.summary,
    ...(topic.steps || []),
    ...(topic.bullets || []),
    ...(topic.terms || []).flat(),
    topic.note || "",
    topic.warning || ""
  ].join(" ").toLocaleLowerCase("ru-RU");
}

export function createHelpScreen({ openSection }) {
  const search = byId("help-search");
  const reset = byId("help-search-reset");
  const topicList = byId("help-topic-list");
  const topicNav = byId("help-topic-nav");
  const summary = byId("help-results-summary");

  function addList(card, items, ordered = false) {
    if (!items?.length) return;
    const list = element(ordered ? "ol" : "ul", "help-list");
    for (const item of items) list.append(element("li", "", item));
    card.append(list);
  }

  function renderTopic(topic) {
    const card = element("article", "panel help-topic");
    card.id = `help-topic-${topic.id}`;
    const head = element("div", "help-topic-head");
    const identity = element("div", "help-topic-identity");
    identity.append(element("span", "help-topic-icon", topic.icon));
    const copy = element("div");
    copy.append(element("h2", "", topic.title), element("p", "muted", topic.summary));
    identity.append(copy);
    head.append(identity);
    if (topic.target) {
      const action = element("button", "secondary help-open-section", `${topic.targetLabel} →`);
      action.type = "button";
      action.onclick = () => openSection(topic.target);
      head.append(action);
    }
    card.append(head);

    if (topic.terms?.length) {
      const terms = element("dl", "help-terms");
      for (const [term, description] of topic.terms) {
        terms.append(element("dt", "", term), element("dd", "", description));
      }
      card.append(terms);
    }
    addList(card, topic.steps, true);
    addList(card, topic.bullets);
    if (topic.note) card.append(element("div", "help-note", topic.note));
    if (topic.warning) card.append(element("div", "help-warning", topic.warning));
    return card;
  }

  function render() {
    const query = search.value.trim().toLocaleLowerCase("ru-RU");
    const visible = query
      ? topics.filter(topic => searchableText(topic).includes(query))
      : topics;
    topicList.replaceChildren();
    topicNav.replaceChildren();

    for (const topic of visible) {
      const navButton = element("button", "help-topic-link", `${topic.icon} ${topic.title}`);
      navButton.type = "button";
      navButton.onclick = () => byId(`help-topic-${topic.id}`).scrollIntoView({
        behavior: "smooth",
        block: "start"
      });
      topicNav.append(navButton);
      topicList.append(renderTopic(topic));
    }

    if (!visible.length) {
      topicList.append(element(
        "div",
        "panel help-empty",
        "Ничего не найдено. Попробуйте название вкладки, сервиса или статуса."
      ));
    }
    summary.textContent = query
      ? `Найдено разделов: ${visible.length}`
      : `Разделов в справке: ${topics.length}`;
    reset.hidden = !query;
  }

  search.addEventListener("input", render);
  reset.onclick = () => {
    search.value = "";
    render();
    search.focus();
  };
  render();

  return { load: render };
}
